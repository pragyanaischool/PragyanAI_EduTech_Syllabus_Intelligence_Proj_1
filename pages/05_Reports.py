def safe_score(
    value,
    default=0.0,
):
    """
    Convert any score-like value into a number
    between 0 and 100.
    """

    try:

        score = float(
            value
        )

    except (
        TypeError,
        ValueError,
    ):

        score = float(
            default
        )


    return round(

        max(

            0.0,

            min(
                100.0,
                score
            )

        ),

        2,

    )


