def normalize_priority(
    priority,
):
    """
    Normalize gap priority.
    """

    value = safe_text(

        priority,

        "Medium",

    ).lower().strip()


    if value in {

        "critical",

        "urgent",

        "very high",

    }:

        return "Critical"


    if value in {

        "high",

        "important",

    }:

        return "High"


    if value in {

        "low",

        "minor",

    }:

        return "Low"


    return "Medium"


