def build_module_map(
    modules_data,
):
    """
    Build a normalized module dictionary.

    Keys:

        module_id
        module_name
        description
        hours
        topics
        concepts
    """

    result = {}


    for index, module in enumerate(

        normalize_list(
            modules_data
        ),

        start=1,

    ):

        if not isinstance(
            module,
            dict,
        ):

            continue


        module_id = safe_text(

            module.get(
                "module_id"
            )

            or

            module.get(
                "unit_id"
            )

            or

            module.get(
                "id"
            )

            or

            f"M{index}"

        )


        module_name = safe_text(

            module.get(
                "module_name"
            )

            or

            module.get(
                "unit_name"
            )

            or

            module.get(
                "name"
            )

            or

            f"Module {index}"

        )


        topics = module.get(

            "topics",

            module.get(
                "units",
                []
            )

        )


        if not isinstance(
            topics,
            list,
        ):

            topics = []


        result[module_id] = {

            "module_id":
                module_id,

            "module_name":
                module_name,

            "description":
                safe_text(
                    module.get(
                        "description"
                    )
                ),

            "purpose":
                safe_text(
                    module.get(
                        "purpose"
                    )
                ),

            "hours":
                safe_number(
                    module.get(
                        "hours",
                        0,
                    )
                ),

            "topics":
                topics,

            "concepts":
                normalize_list(
                    module.get(
                        "concepts",
                        []
                    )
                ),

        }


    return result


