# 61. TEXT SIMILARITY
# ============================================================

def text_similarity(
    first,
    second,
):
    """
    Lightweight lexical similarity.

    This is used only for reporting/comparison.
    The actual semantic intelligence is generated by the
    Curriculum Intelligence agents.
    """

    first_words = normalized_words(
        first
    )


    second_words = normalized_words(
        second
    )


    if not first_words or not second_words:

        return 0.0


    intersection = (

        first_words
        &
        second_words

    )


    union = (

        first_words
        |
        second_words

    )


    if not union:

        return 0.0


    return round(

        (
            len(
                intersection
            )
            /
            len(
                union
            )
        )
        *
        100,

        2,

    )


