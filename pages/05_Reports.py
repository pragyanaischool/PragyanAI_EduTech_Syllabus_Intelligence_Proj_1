def normalize_outcome(
    outcome,
    prefix,
    index,
):
    """
    Normalize CO / PO / PSO records.
    """

    if isinstance(
        outcome,
        dict,
    ):

        code = (

            outcome.get(
                "code"
            )

            or

            outcome.get(
                "id"
            )

            or

            f"{prefix}{index}"

        )


        description = (

            outcome.get(
                "description"
            )

            or

            outcome.get(
                "text"
            )

            or

            outcome.get(
                "outcome"
            )

            or

            outcome.get(
                "name"
            )

        )


        return {

            "code":
                safe_text(
                    code
                ),

            "description":
                safe_text(
                    description
                ),

            "bloom_level":
                safe_text(

                    outcome.get(
                        "bloom_level"
                    )

                ),

            "domain":
                safe_text(

                    outcome.get(
                        "domain"
                    )

                ),

        }


    return {

        "code":
            f"{prefix}{index}",

        "description":
            safe_text(
                outcome
            ),

        "bloom_level":
            "",

        "domain":
            "",

    }


