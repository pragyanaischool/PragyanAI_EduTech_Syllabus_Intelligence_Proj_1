def maturity_level(
    score,
):
    """

    Convert overall score into an institutional
    curriculum maturity classification.
    """

    score = safe_score(
        score
    )


    if score >= 90:

        return (
            "Industry Ready",
            "Excellent alignment with industry and "
            "strong curriculum structure."
        )


    if score >= 75:

        return (
            "Advanced",
            "Strong curriculum with selected areas "
            "requiring enhancement."
        )


    if score >= 60:

        return (
            "Developing",
            "Curriculum has a reasonable foundation "
            "but significant enhancement is recommended."
        )


    if score >= 40:

        return (
            "Needs Improvement",
            "Multiple curriculum and industry gaps "
            "require structured intervention."
        )


    return (
        "Critical",
        "Major curriculum restructuring is recommended."
    )


