def calculate_gap_severity(
    category,
    item,
):
    """
    Estimate severity when the AI agent has not explicitly
    provided severity.

    This is a reporting fallback only.
    """

    category = safe_text(
        category
    ).lower()


    text = safe_text(
        item
    ).lower()


    high_terms = [

        "llm",

        "generative ai",

        "machine learning",

        "deep learning",

        "python",

        "sql",

        "cloud",

        "aws",

        "azure",

        "docker",

        "kubernetes",

        "langchain",

        "langgraph",

        "rag",

        "agent",

        "data science",

        "cybersecurity",

        "computer vision",

        "nlp",

    ]


    if any(

        term in text

        for term in high_terms

    ):

        return "High"


    if category in {

        "skill",

        "technology",

        "tool",

        "project",

    }:

        return "Medium"


    return "Low"


