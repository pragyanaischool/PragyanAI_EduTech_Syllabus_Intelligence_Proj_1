def create_gap_record(
    category,
    item,
    priority=None,
    source="AI Gap Analysis",
    recommendation="",
    module="",
):
    """
    Create a normalized gap object.
    """

    item_text = safe_text(
        item
    )


    if not item_text:

        return None


    if priority:

        normalized_priority = normalize_priority(

            priority

        )

    else:

        normalized_priority = (

            calculate_gap_severity(

                category,

                item_text,

            )

        )


    category_score = category_gap_score(

        category

    )


    priority_multiplier = {

        "Critical":
            1.00,

        "High":
            0.90,

        "Medium":
            0.70,

        "Low":
            0.45,

    }.get(

        normalized_priority,

        0.70,

    )


    gap_score = round(

        category_score
        *
        priority_multiplier,

        2,

    )


    if not recommendation:

        recommendation = (

            f"Add or strengthen {item_text} "
            f"within the curriculum."

        )


    return {

        "category":
            safe_text(
                category
            ).title(),

        "gap":
            item_text,

        "priority":
            normalized_priority,

        "gap_score":
            gap_score,

        "source":
            source,

        "module":
            module,

        "recommendation":
            recommendation,

    }


