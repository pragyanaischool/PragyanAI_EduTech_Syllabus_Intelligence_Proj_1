def build_topic_map(
    modules_data,
):
    """
    Create a topic-level lookup.
    """

    result = {}


    module_map = build_module_map(
        modules_data
    )


    for module_id, module in module_map.items():

        topics = module.get(
            "topics",
            []
        )


        for index, raw_topic in enumerate(

            topics,

            start=1,

        ):

            topic = normalize_topic(

                raw_topic,

                index,

            )


            topic_id = topic[
                "topic_id"
            ]


            key = (

                f"{module_id}::"
                f"{topic_id}"

            )


            result[key] = {

                **topic,

                "module_id":
                    module_id,

                "module_name":
                    module.get(
                        "module_name"
                    ),

            }


    return result


