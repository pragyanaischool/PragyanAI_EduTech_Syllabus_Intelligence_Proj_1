# 17. EMPTY STATE CHECK
# ============================================================

def has_data(
    value,
):
    """
    Check whether a structure contains useful data.
    """

    if value is None:

        return False


    if isinstance(
        value,
        (list, tuple, set, dict),
    ):

        return len(
            value
        ) > 0


    if isinstance(
        value,
        str,
    ):

        return bool(
            value.strip()
        )


    return True


