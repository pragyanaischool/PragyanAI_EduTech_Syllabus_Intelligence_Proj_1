def first_available_list(
    data,
    keys,
):
    """
    Return the first available list from a dictionary.
    """

    if not isinstance(
        data,
        dict,
    ):

        return []


    for key in keys:

        value = data.get(
            key
        )


        if isinstance(
            value,
            list,
        ):

            return value


    return []


