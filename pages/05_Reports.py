def normalize_jd_skill(
    skill,
):
    """
    Normalize JD/curriculum skill strings.

    This reporting matcher is intentionally conservative.
    The authoritative semantic match comes from the
    Industry/JD Intelligence module.
    """

    text = safe_text(
        skill
    ).lower().strip()


    text = re.sub(

        r"[^a-z0-9+#.\-\s]",

        " ",

        text,

    )


    text = re.sub(

        r"\s+",

        " ",

        text,

    ).strip()


    aliases = {

        "ml":
            "machine learning",

        "machine-learning":
            "machine learning",

        "dl":
            "deep learning",

        "deep-learning":
            "deep learning",

        "gen ai":
            "generative ai",

        "genai":
            "generative ai",

        "artificial intelligence":
            "artificial intelligence",

        "ai":
            "artificial intelligence",

        "natural language processing":
            "nlp",

        "large language model":
            "llm",

        "large language models":
            "llm",

        "llms":
            "llm",

    }


    return aliases.get(
        text,
        text,
    )


