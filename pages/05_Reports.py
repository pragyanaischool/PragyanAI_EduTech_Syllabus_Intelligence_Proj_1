# 181. CO-PO MATRIX NORMALIZATION
# ============================================================

def normalize_matrix(
    matrix,
):
    """
    Normalize CO-PO / CO-PSO matrix.

    Supports:

        dict of dict

        list of dict

        list of lists
    """

    if isinstance(
        matrix,
        dict,
    ):

        return matrix


    if not isinstance(
        matrix,
        list,
    ):

        return {}


    result = {}


    for row_index, row in enumerate(

        matrix,

        start=1,

    ):

        if isinstance(
            row,
            dict,
        ):

            row_code = (

                row.get(
                    "co"
                )

                or

                row.get(
                    "code"
                )

                or

                f"CO{row_index}"

            )


            values = {}

            for key, value in row.items():

                if key in {

                    "co",

                    "code",

                    "description",

                }:

                    continue


                values[
                    safe_text(
                        key
                    )
                ] = value


            result[
                safe_text(
                    row_code
                )
            ] = values


        elif isinstance(
            row,
            list,
        ):

            result[
                f"CO{row_index}"
            ] = {

                f"PO{column_index}":
                    value

                for column_index, value

                in enumerate(

                    row,

                    start=1,

                )

            }


    return result


