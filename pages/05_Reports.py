# 18. SAFE PERCENTAGE
# ============================================================

def percentage(
    numerator,
    denominator,
):
    """
    Safe percentage calculation.
    """

    numerator = safe_number(
        numerator
    )


    denominator = safe_number(
        denominator
    )


    if denominator == 0:

        return 0.0


    return round(

        (
            numerator
            /
            denominator
        )
        *
        100,

        2,

    )


# ============================================================
# 19. SCORE LABEL
# ============================================================

def score_label(
    score,
):
    """
    Convert percentage score into human-readable status.
    """

    score = safe_number(
        score
    )


    if score >= 90:

        return "Excellent"


    if score >= 80:

        return "Very Strong"


    if score >= 70:

        return "Strong"


    if score >= 60:

        return "Moderate"


    if score >= 50:

        return "Needs Improvement"


    return "Critical"


