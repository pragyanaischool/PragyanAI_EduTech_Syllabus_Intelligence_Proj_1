def html_escape(
    value,
):
    """
    Safely convert arbitrary values into HTML text.
    """

    try:

        from html import escape

        return escape(

            safe_text(
                value
            )

        )

    except Exception:

        return safe_text(
            value
        )


# ============================================================
# 241. HTML TABLE HELPER
# ============================================================

def dataframe_to_html(
    dataframe,
):
    """
    Convert a DataFrame into readable HTML.
    """

    if dataframe is None:

        return (
            "<p>No data available.</p>"
        )


    if dataframe.empty:

        return (
            "<p>No data available.</p>"
        )


    try:

        return dataframe.to_html(

            index=False,

            border=0,

            classes="report-table",

            escape=True,

        )

    except Exception:

        return (
            "<p>Unable to generate table.</p>"
        )


# ============================================================
# 242. LIST TO HTML
# ============================================================

def list_to_html(
    items,
):
    """
    Convert a list into HTML bullets.
    """

    if not items:

        return (
            "<p>No information available.</p>"
        )


    html_items = []


    for item in items:

        if isinstance(
            item,
            dict,
        ):

            title = (

                item.get(
                    "title"
                )

                or

                item.get(
                    "name"
                )

                or

                item.get(
                    "recommendation"
                )

                or

                item.get(
                    "gap"
                )

                or

                item.get(
                    "skill"
                )

                or

                item.get(
                    "topic"
                )

                or

                ""

            )


            html_items.append(

                f"<li>{html_escape(title)}</li>"

            )

        else:

            html_items.append(

                f"<li>{html_escape(item)}</li>"

            )


    return (

        "<ul>"

        +

        "".join(
            html_items
        )

        +

        "</ul>"

    )


