# 13. SERIALIZE JSON
# ============================================================

def serialize_json(
    data,
):
    """
    Serialize object for Streamlit download.
    """

    try:

        return json.dumps(

            data,

            indent=2,

            ensure_ascii=False,

            default=str,

        )

    except Exception:

        return json.dumps(

            {
                "error":
                    "Unable to serialize report."
            },

            indent=2,

        )


# ============================================================
# 14. JSON BYTES
# ============================================================

def json_bytes(
    data,
):
    """
    Convert JSON to UTF-8 bytes.
    """

    return serialize_json(
        data
    ).encode(
        "utf-8"
    )


