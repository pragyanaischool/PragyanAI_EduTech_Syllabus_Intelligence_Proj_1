# 9. SAFE TEXT
# ============================================================

def safe_text(
    value,
    default="",
):
    """
    Convert arbitrary values into safe display text.
    """

    if value is None:

        return default


    if isinstance(
        value,
        str,
    ):

        return value.strip()


    if isinstance(
        value,
        (int, float),
    ):

        return str(
            value
        )


    if isinstance(
        value,
        list,
    ):

        return ", ".join(

            safe_text(
                item
            )

            for item in value

        )


    if isinstance(
        value,
        dict,
    ):

        return json.dumps(

            value,

            ensure_ascii=False,

        )


    return str(
        value
    )


# ============================================================
# 10. SAFE NUMBER
# ============================================================

def safe_number(
    value,
    default=0,
):
    """
    Convert a value into a numeric value.
    """

    if value is None:

        return default


    if isinstance(
        value,
        bool,
    ):

        return int(
            value
        )


    try:

        return float(
            value
        )

    except Exception:

        return default


# ============================================================
# 11. NORMALIZE LIST
# ============================================================

def normalize_list(
    value,
):
    """
    Convert common structures into a clean list.
    """

    if value is None:

        return []


    if isinstance(
        value,
        list,
    ):

        return [

            item

            for item in value

            if item is not None

        ]


    if isinstance(
        value,
        tuple,
    ):

        return list(
            value
        )


    if isinstance(
        value,
        set,
    ):

        return list(
            value
        )


    if isinstance(
        value,
        str,
    ):

        if not value.strip():

            return []


        return [

            value.strip()

        ]


    return [
        value
    ]


# ============================================================
# 12. UNIQUE VALUES
# ============================================================

def unique_values(
    values,
):
    """
    Preserve order while removing duplicates.
    """

    result = []

    seen = set()


    for value in normalize_list(
        values
    ):

        text = safe_text(
            value
        )


        key = text.lower().strip()


        if not key:

            continue


        if key in seen:

            continue


        seen.add(
            key
        )


        result.append(
            value
        )


    return result


