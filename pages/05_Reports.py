def calculate_collection_match(
    required,
    available,
):
    """
    Compare two collections using normalized names.
    """

    required_map = {

        normalize_jd_skill(
            item
        ):
            item

        for item in normalize_list(
            required
        )

    }


    available_map = {

        normalize_jd_skill(
            item
        ):
            item

        for item in normalize_list(
            available
        )

    }


    if not required_map:

        return {

            "required":
                [],

            "matched":
                [],

            "missing":
                [],

            "coverage":
                0.0,

        }


    matched = [

        available_map[key]

        for key in required_map

        if key in available_map

    ]


    missing = [

        required_map[key]

        for key in required_map

        if key not in available_map

    ]


    return {

        "required":
            list(
                required_map.values()
            ),

        "matched":
            matched,

        "missing":
            missing,

        "coverage":
            percentage(
                len(
                    matched
                ),
                len(
                    required_map
                ),
            ),

    }


