def normalized_words(
    value,
):
    """
    Convert text into a normalized word set.
    """

    text = safe_text(
        value
    ).lower()


    text = re.sub(
        r"[^a-z0-9\s]",
        " ",
        text,
    )


    words = [

        word

        for word in text.split()

        if len(
            word
        ) > 2

    ]


    return set(
        words
    )


